//! # Usage
//!
//! We call `nexus-db-queries` the upstream crate, and `omicron-nexus` the
//! downstream crate.
//!
//! First, for each shard, create a crate that depends on the upstream crate and
//! on `preinstantiate`. Turn on the `build` feature for the build script:
//!
//! ```toml
//! [dependencies]
//! nexus-db-queries.workspace = true
//! preinstantiate.workspace = true
//!
//! [build-dependencies]
//! preinstantiate = { workspace = true, features = ["build"] }
//! ```
//!
//! Put the shared configuration in a file that each build script `include!`s.
//! For example, with the shard crates in a `shards` directory:
//!
//! ```rust,ignore
//! // shards/preinstantiate_config.rs
//! fn config(shard: ShardIndex) -> Config {
//!     Config::new("../../nexus-db-queries/src/lib.rs", shard)
//!         .add_async_inherent_methods("nexus_db_queries::db::DataStore")
//! }
//! ```
//!
//! Each shard's build script then only says which shard it is:
//!
//! ```rust,ignore
//! // shards/shard0/build.rs
//! use preinstantiate::build::{Config, ShardIndex, run_build_script_or_exit};
//!
//! include!("../preinstantiate_config.rs");
//!
//! fn main() {
//!     let shard = ShardIndex::new(0, 8).expect("shard 0 of 8 is valid");
//!     run_build_script_or_exit(&config(shard));
//! }
//! ```
//!
//! Note that the `include!` path is relative to `build.rs`, but the crate root
//! passed to [`Config::new`](build::Config::new) is relative to each shard's
//! own directory. This works out because every shard crate is at the same
//! depth.
//!
//! `preinstantiate` will do a source analysis to find `pub async` methods
//! defined on `DataStore` filtered to that shard, and write out a function
//! which forces code for that shard to be generated. In the shard's `lib.rs`,
//! include it:
//!
//! ```rust,ignore
//! include!(concat!(env!("OUT_DIR"), "/preinstantiate_async_fns.rs"));
//!
//! use nexus_db_queries as _;
//! use preinstantiate as _;
//! ```
//!
//! (The `use` statements are required by Rust 1.100's unused dependencies
//! lint.)
//!
//! Finally, in the downstream crate, add dependencies and `use` statements for
//! all the shard crates:
//!
//! ```rust,ignore
//! use nexus_db_queries_preinstantiate_0 as _;
//! use nexus_db_queries_preinstantiate_1 as _;
//! ```
//!
//! For a working example, see [`e2e-example`].
//!
//! [`e2e-example`]: https://github.com/oxidecomputer/preinstantiate/tree/main/e2e-example
//!
//! ## Analysis limits
//!
//! `preinstantiate` does a source-level analysis of the upstream crate. We are
//! conservative and skip over methods that:
//!
//! * Are generic over types or consts (lifetimes are fine).
//! * Accept an `impl Trait` argument.
//! * Are `unsafe`.
//! * Have a `cfg` or `cfg_attr` attribute, or are inside an `impl` block
//!   gated that way.
//! * Are in a module declared with `#[path]`.
//! * Accept more than [`MAX_ARITY`] arguments, including `self`.
//!
//! We don't have to be perfect to realize the build time improvements — it is
//! sufficient to instantiate the vast majority of async functions.
//!
//! ## Skipping methods
//!
//! Some methods can't be pre-instantiated for reasons that cannot be determined
//! by a source-level analysis. For example, a `pub async fn` whose signature
//! mentions a non-public type is accepted by the Rust compiler in the upstream
//! crate, but it can't be referred to within any of the shard crates. To skip
//! such methods, use [`Config::skip_method`](build::Config::skip_method):
//!
//! ```rust,ignore
//! Config::new("../../nexus-db-queries/src/lib.rs", shard)
//!     .add_async_inherent_methods("nexus_db_queries::db::DataStore")
//!     .skip_method("nexus_db_queries::db::DataStore", "silo_delete_internal")
//! ```
//!
//! ## Debugging
//!
//! To check whether `preinstantiate` is working as expected, pick a method and
//! compare how many copies of it are compiled with share-generics on
//! and off:
//!
//! ```console
//! $ cargo rustc -p omicron-nexus --lib -- -Zprint-mono-items=yes \
//!     | grep -c 'DataStore>::silo_delete'
//! $ cargo rustc -p omicron-nexus --lib -- \
//!     -Zprint-mono-items=yes -Zshare-generics=no \
//!     | grep -c 'DataStore>::silo_delete'
//! ```
//!
//! The two numbers should be relatively far from each other. If they are close
//! to each other, `preinstantiate` is not working or not providing any benefit.
//!
//! The build script writes a report to
//! `OUT_DIR/preinstantiate_async_fns-report.txt` with information about
//! included and skipped methods.
//!
//! ## Release builds
//!
//! If share-generics is off, the preinstantiate scheme doesn't work. With
//! current versions of Rust, share-generics is off in release builds, so
//! `preinstantiate` disables itself.
//!
//! [^opt-level]: More specifically, `share-generics` are enabled under
//!   opt-level 0, 1, `s`, and `z`, but not 2 or 3.

