use std::{
    future::Future,
    pin::Pin,
    task::{Context, Poll},
};

#[cfg(feature = "build")]
pub mod build;

macro_rules! arguments_noun {
    (1) => {
        "argument"
    };
    ($count:literal) => {
        "arguments"
    };
}

macro_rules! preinstantiate_async_fn_impls {
    ($($count:tt: $name:ident($($arg:ident),*);)*) => {
        $(
            const _: () = assert!(
                $count == <[&str]>::len(&[$(stringify!($arg)),*]),
                concat!("wrong argument count for ", stringify!($name)),
            );

            #[doc = concat!(
                "Pre-instantiate an async function with ",
                $count,
                " ",
                arguments_noun!($count),
                ".",
            )]
            #[inline(never)]
            pub fn $name<F, Fut, $($arg),*>(_f: F)
            where
                F: Fn($($arg),*) -> Fut,
                Fut: Future,
            {
                // Taking these function pointers makes the calling crate
                // compile the future's poll and drop glue, without actually
                // calling or boxing anything.
                let poll: fn(
                    Pin<&mut Fut>,
                    &mut Context<'_>,
                ) -> Poll<Fut::Output> = <Fut as Future>::poll;
                let drop: unsafe fn(*mut Fut) = std::ptr::drop_in_place::<Fut>;
                std::hint::black_box((poll, drop));
            }
        )*

        /// The maximum number of supported arguments for `preinstantiate`.
        ///
        /// A method with more than these many arguments will be ignored. As
        /// documented at the [crate level](crate), this is a conservative
        /// approximation that is fine.
        pub const MAX_ARITY: usize = {
            let arities: &[usize] = &[$($count),*];
            let mut max = 0;
            let mut i = 0;
            while i < arities.len() {
                if arities[i] > max {
                    max = arities[i];
                }
                i += 1;
            }
            max
        };
    };
}

