//!
//! The Rust compiler has an option called _share-generics_ which helps here.
//! When this option is enabled, downstream crates can reuse monomorphized code
//! generated by upstream crates. In Rust 1.100, share-generics is enabled for
//! dev builds but not release builds[^opt-level].
//!
//! With share-generics, if some crate upstream of `omicron-nexus` generates
//! code for `silo_delete`, `omicron-nexus` can use it. `preinstantiate` is a
//! way to set up that scenario above. (The name comes from [explicit template
//! instantiation], which solves a similar problem in C++.)
//!
//! [explicit template instantiation]: https://stackoverflow.com/questions/2351148/explicit-template-instantiation-when-is-it-used
//!
//! ## Why separate crates?
//!
//! We could force code generation within `nexus-db-queries`. But when
//! share-generics is on, rustc can't write out a crate's metadata until it has
//! worked out which monomorphized functions will be exported by it. Downstream
//! crates cannot start compiling until this metadata has been written out. In
//! Omicron, same-crate preinstantiation was observed to cause builds to be
//! 10-15% slower.
//!
//! So instead of being in the same crate, `preinstantiate` forces code
//! generation within a few _shard_ crates. (Each source file is assigned to a
//! shard by hash.) Each shard depends only on the upstream crate, so shards
//! can build in parallel with each other.
