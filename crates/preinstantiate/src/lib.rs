//! `preinstantiate` makes one crate compile the `pub async fn` bodies of
//! another crate, so that downstream crates don't have to compile those bodies
//! themselves.
//!
//! In [Omicron](https://github.com/oxidecomputer/omicron), after an edit to a
//! `nexus-db-queries` method, rebuilding `omicron-nexus` goes from around 33
//! seconds to around 13. (This was measured with Rust 1.99.1 on a computer with
//! an AMD Ryzen 9 7950X processor running Linux.)
//!
//! # Motivation
//!
//! Let's say `nexus-db-queries` has a method like this:
//!
//! ```rust,ignore
//! impl DataStore {
//!     pub async fn silo_delete(&self, id: SiloId) -> Result<(), Error> {
//!         // ...
//!     }
//! }
//! ```
//!
//! You might ordinarily expect the compile process for `nexus-db-queries` to
//! generate code for the body of `silo_delete`. But in reality it is treated as
//! _monomorphized_, similar to a generic function. With monomorphized
//! functions, only higher-level instructions for how to compile code are
//! generated, and the actual code is only generated when the function is
//! instantiated with specific types.
//!
//! <details>
//!
//! <summary>Why is this the case?</summary>
//!
//! A function like `silo_delete` isn't actually generic. Why does it need to be
//! monomorphized?
//!
//! This looks like a little bit of an accident! In Rust 1.100, treating
//! functions as monomorphized like this is restricted to `pub async` functions
//! associated with a type, like `DataStore::silo_delete`. It does not apply to
//! `pub async` module-level (free) functions, which _are_ generated at the
//! place they're defined. Based on [rust-lang/rust#143290] this doesn't
//! seem intentional, at least at first glance; someone in the Rust community
//! could reasonably notice and fix this.
//!
//! What if this is fixed in `rustc`? Since it would mean code is generated
//! within the crate, it's a bit of a mixed bag.
//!
//! * If you aren't using `preinstantiate`, it is definitely a win. Most people
//!   aren't.
//! * If you _are_ using `preinstantiate`, though, a fix to `rustc` would make
//!   life significantly worse for you: as measured here, your incremental build
//!   times would double!
//!
//! In empirical testing against a patched `rustc`, the result is roughly the
//! same as "In nexus-db-queries" in the build performance chart below. This
//! makes sense because fixing this in `rustc` is roughly equivalent to that.
//!
//! The upshot of all this is that `preinstantiate` has a bit of a fleeting
//! nature. This does expose a fairly deep structural problem in the Rust
//! compiler, though, where there isn't sufficient pipelining happening during
//! the build. Maybe `preinstantiate` will add to the pressure to fix pipelining
//! properly. Maybe it won't. C'est la vie.
//!
//! [rust-lang/rust#143290]: https://github.com/rust-lang/rust/pull/143290
//!
//! </details>
//!
//! Anyway, accepting that this is the case, the code for this function is
//! generated at the call site in `omicron-nexus`, not within
//! `nexus-db-queries`. In Omicron's case this adds up a lot of code, all of
//! which is generated towards the end of the build process within
//! `omicron-nexus`.
